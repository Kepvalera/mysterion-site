// Reproducible, pinned vendor extraction. Run explicitly; never runs at deployment.
import fs from 'node:fs/promises';
import {gunzipSync} from 'node:zlib';
import {createHash} from 'node:crypto';
const version='4.13.0';
const integrity='sha512-GrWl7wsV46fKIXQZB5ebskLZLAmKL6d9RS0fspCxDeQyjoNu1AfTJTMLPOJyfzaQm0ldFiwFN21/w+sE/kgEFQ==';
const response=await fetch(`https://registry.npmjs.org/hash-wasm/-/hash-wasm-${version}.tgz`);
if(!response.ok)throw Error('Vendor download failed');
const tarball=Buffer.from(await response.arrayBuffer());
if('sha512-'+createHash('sha512').update(tarball).digest('base64')!==integrity)throw Error('Vendor integrity mismatch');
const tar=gunzipSync(tarball),files=new Map();
for(let offset=0;offset+512<=tar.length;){
 const name=tar.subarray(offset,offset+100).toString().replace(/\0.*$/s,''),size=parseInt(tar.subarray(offset+124,offset+136).toString().replace(/\0.*$/s,'').trim(),8)||0;
 if(!name)break;files.set(name,tar.subarray(offset+512,offset+512+size));offset+=512+Math.ceil(size/512)*512;
}
let code=files.get('package/dist/argon2.umd.min.js')?.toString();
if(!code)throw Error('Vendor source missing');
const dir='media-worker/vendor/hash-wasm';await fs.mkdir(dir,{recursive:true});
const modules=[];
code=code.replace(/name:"([^"]+)",data:"([^"]+)"/g,(_,name,data)=>{
 if(!['argon2','blake2b'].includes(name))throw Error('Unexpected WASM module');
 modules.push({name,bytes:Buffer.from(data,'base64')});return `name:"${name}",data:""`;
});
if(modules.length!==2)throw Error('Expected two WASM modules');
const opening=code.indexOf('function(A){"use strict";'),ending=code.lastIndexOf('});');
if(opening<0||ending<opening)throw Error('Unexpected vendor wrapper');
code=code.slice(opening+'function(A){"use strict";'.length,ending);
const compile='const I=a(A.data),i=WebAssembly.compile(I.buffer);S.set(A.name,i)';
if(code.split(compile).length!==2||code.split('WebAssembly.instantiate(I,{})').length!==2)throw Error('Unexpected WASM loader');
code=code.replace(compile,'S.set(A.name,Promise.resolve(wasmModules[A.name]))').replace('WebAssembly.instantiate(I,{})','instantiate(I)');
const wrapper=`// hash-wasm ${version}, MIT. Generated by tools/vendor-hash-wasm.mjs.\nimport argon2 from './argon2.wasm';\nimport blake2b from './blake2b.wasm';\nconst wasmModules={argon2,blake2b};\n// Factory scopes upstream caches and mutexes to ONE KDF operation, never a request queue.\nexport function createArgon2(){\n const A={},instances=[];\n function instantiate(module){const instance=new WebAssembly.Instance(module,{});instances.push(instance);return instance}\n ${code}\n return {argon2id:A.argon2id,destroy(){for(const instance of instances)new Uint8Array(instance.exports.memory.buffer).fill(0);instances.length=0}};\n}\n`;
await fs.writeFile(dir+'/argon2.mjs',wrapper);
await fs.writeFile(dir+'/LICENSE',files.get('package/LICENSE'));
for(const module of modules)await fs.writeFile(`${dir}/${module.name}.wasm`,module.bytes);
await fs.writeFile(dir+'/provenance.json',JSON.stringify({package:'hash-wasm',version,integrity,source:'https://github.com/Daninet/hash-wasm',adaptations:['static WASM imports instead of runtime compilation','request-local factory for all upstream state','wipe instance memory after each operation'],files:Object.fromEntries([['argon2.mjs',Buffer.from(wrapper)],...modules.map(m=>[m.name+'.wasm',m.bytes])].map(([name,bytes])=>[name,createHash('sha256').update(bytes).digest('hex')]))},null,2)+'\n');
console.log(JSON.stringify({version,integrityVerified:true,modules:modules.map(m=>({name:m.name,bytes:m.bytes.length}))}));
