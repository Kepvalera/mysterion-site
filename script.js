// Progressive enhancement: subtle section reveals and scroll feedback.
(() => {
  const reduceMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  const progress = document.querySelector('.reading-progress');
  const header = document.querySelector('.site-header');
  let scrollPending = false;
  let maxScroll = 1;
  const measureScroll = () => {
    maxScroll = Math.max(1, document.documentElement.scrollHeight - window.innerHeight);
  };
  measureScroll();
  // Translations, expanded biographies/FAQ and decoded photos can change the
  // document height without a window resize. Keep the progress denominator fresh.
  if ('ResizeObserver' in window) {
    new ResizeObserver(() => { measureScroll(); updateScroll(); }).observe(document.body);
  }
  let wasScrolled = false;
  const updateScroll = () => {
    const y = window.scrollY || window.pageYOffset || 0;
    if (progress) progress.style.transform = `scaleX(${Math.min(1, Math.max(0, y / maxScroll))})`;
    const isScrolled = y > 24;
    if (header && isScrolled !== wasScrolled) {
      header.classList.toggle('is-scrolled', isScrolled);
      wasScrolled = isScrolled;
    }
    scrollPending = false;
  };
  window.addEventListener('scroll', () => {
    if (!scrollPending) { scrollPending = true; window.requestAnimationFrame(updateScroll); }
  }, {passive:true});
  window.addEventListener('resize', () => { measureScroll(); updateScroll(); }, {passive:true});
  updateScroll();
  if (reduceMotion || !('IntersectionObserver' in window)) return;
  const targets = document.querySelectorAll('.section-heading, .section-topline, .section-number, .about-copy, .founders-visual, .founders-text, .pillar, .ministry-card, .event-card, .media-card, .vision-content, .faq-grid, .contact-grid');
  const observer = new IntersectionObserver((entries) => {
    for (const entry of entries) {
      if (!entry.isIntersecting) continue;
      entry.target.classList.add('motion-visible');
      observer.unobserve(entry.target);
    }
  }, {threshold:0.08,rootMargin:'0px 0px -24px 0px'});
  targets.forEach((element, index) => {
    element.classList.add('motion-reveal');
    // Stagger only nearby card groups, not whole-page content.
    if (element.matches('.pillar, .ministry-card, .media-card')) {
      const siblings = Array.from(element.parentElement.children).filter(el => el.matches('.pillar, .ministry-card, .media-card'));
      element.style.setProperty('--motion-delay', `${Math.min(siblings.indexOf(element) % 3, 2) * 90}ms`);
    }
    observer.observe(element);
  });
  document.documentElement.classList.add('motion-ready');
})();

